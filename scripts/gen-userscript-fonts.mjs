// Converts MathJax's dynamic SVG font ranges (ES modules that call MathJaxNewcmFont.dynamicSetup)
// into plain JSON data for the userscript, plus a SHA-256 manifest that is compiled INTO the
// userscript. At runtime the userscript downloads a range, verifies its hash and calls
// dynamicSetup itself - no eval, no remote code, and a tampered file is rejected.
//
// Output: userscript/fonts/<range>.json (committed, served from the tagged repo by jsDelivr /
// GitHub raw) and src/userscript/fontManifest.ts.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { pathToFileURL, fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = path.dirname(require.resolve('@mathjax/mathjax-newcm-font/package.json'));
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const dynDir = path.join(pkgDir, 'mjs/svg/dynamic');

const { MathJaxNewcmFont } = await import(pathToFileURL(path.join(pkgDir, 'mjs/svg.js')).href);
const captured = new Map();
MathJaxNewcmFont.dynamicSetup = (ext, file, variants, delimiters = {}, fonts = null) => {
  captured.set(file, { ext, file, variants, delimiters, fonts });
};

const outDir = path.join(root, 'userscript/fonts');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const manifest = {};
let total = 0;
for (const f of fs.readdirSync(dynDir).filter((f) => f.endsWith('.js')).sort()) {
  const name = f.slice(0, -3);
  await import(pathToFileURL(path.join(dynDir, f)).href);
  const data = captured.get(name);
  if (!data) throw new Error(`${f} did not call dynamicSetup('${name}')`);
  const json = JSON.stringify(data);
  // Round-trip check: the data must survive JSON unchanged (no functions / undefined / NaN).
  if (JSON.stringify(JSON.parse(json)) !== json) throw new Error(`${name} is not JSON-safe`);
  fs.writeFileSync(path.join(outDir, `${name}.json`), json);
  manifest[name] = crypto.createHash('sha256').update(json).digest('hex');
  total += json.length;
}

const ts = `// Generated by scripts/gen-userscript-fonts.mjs - do not edit.
// SHA-256 of each dynamic font range served from userscript/fonts/ (${pkg.name}@${pkg.version}).
export const FONT_PACKAGE = ${JSON.stringify(`${pkg.name}@${pkg.version}`)};
export const FONT_HASHES: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src/userscript/fontManifest.ts'), ts);
console.log(`wrote ${Object.keys(manifest).length} font ranges (${(total / 1024 / 1024).toFixed(1)} MiB) for ${pkg.name}@${pkg.version}`);
