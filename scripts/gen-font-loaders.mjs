// Generates src/render/fontLoaders.ts (used by the Node unit tests only; the extension build
// loads the same files as separate entries by URL, see vite.config.ts).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const pkg = path.dirname(require.resolve('@mathjax/mathjax-newcm-font/package.json'));
const dir = path.join(pkg, 'mjs', 'svg', 'dynamic');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js')).map((f) => f.slice(0, -3)).sort();
const lines = files.map((f) => `  '${f}': () => import('@mathjax/mathjax-newcm-font/mjs/svg/dynamic/${f}.js'),`);
const out = `// Generated by scripts/gen-font-loaders.mjs - do not edit.\nexport const fontLoaders: Record<string, () => Promise<unknown>> = {\n${lines.join('\n')}\n};\n`;
fs.writeFileSync(new URL('../src/render/fontLoaders.ts', import.meta.url), out);
console.log(`wrote ${files.length} font loaders`);
